int value = 1;

// ++ incrementa 1 na variaável value 
value++;
Console.WriteLine($"incremento: {value}");

// += soma value(1) com 5 
value += 5;
Console.WriteLine($"Incremento: {value}");

// -+ decrementa 5 do value
value -= 5;
Console.WriteLine($"decremento: {value} ");

// -- decrementa 1 do value
value--;
Console.WriteLine($"decremento: {value}");

